def get_city_data(city: str) -> dict | None:
    """获取城市经济数据"""
    return CITY_ECONOMIC_DATA.get(city)


def get_city_tier(city: str) -> str | None:
    """获取城市等级"""
    data = get_city_data(city)
    return data.get("tier") if data else None


def get_hourly_rate(city: str, skill_category: str = "基础技能") -> float | None:
    """估算城市时薪"""
    data = get_city_data(city)
    if data:
        return data.get("hourly_rates", {}).get(skill_category)
    return None


def get_market_density(city: str) -> dict:
    """获取市场密度"""
    data = get_city_data(city)
    return data.get("market_density", {}) if data else {}


def get_policy_benefits(city: str) -> list:
    """获取城市政策福利"""
    data = get_city_data(city)
    return data.get("policy_benefits", []) if data else []